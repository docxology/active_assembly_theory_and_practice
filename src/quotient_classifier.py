def _pad_nops(code: bytes, count: int) -> bytes:
    if count < 0:
        raise ValueError("NOP count must be non-negative")
    return code + (b"\x90" * count)


def _token(observation: TypedObservation) -> str:
    """Encode only typed observation fields; omit mnemonic, bytes, and address."""

    values = [
        typed_field_value(observation, field) for field in TYPED_OBSERVATION_FIELDS
    ]
    return "|".join(values)


def _trace_summary(
    code: bytes, initial_rax: int
) -> tuple[tuple[str, ...], dict[str, float]]:
    instructions = disassemble_bytes(code)
    trace = emulate_x86_64(code, initial_rax=initial_rax)
    typed = encode_typed_observations(instructions, trace)
    counts: dict[str, float] = {
        "static_instruction_count": float(len(instructions)),
        "executed_instruction_count": float(trace.instruction_count),
        "memory_event_count": float(len(trace.memory_events)),
        "executed_fraction": float(trace.instruction_count / len(instructions)),
        "initial_rax_is_zero": float(initial_rax == 0),
    }
    for field, values in _FIELD_VALUES.items():
        for value in values:
            counts[f"{field}::{value}"] = float(
                sum(typed_field_value(item, field) == value for item in typed)
            )
    counts["register_read_nonempty"] = float(
        sum(bool(item.register_read_set) for item in typed)
    )
    counts["register_write_nonempty"] = float(
        sum(bool(item.register_write_set) for item in typed)
    )
    return tuple(_token(item) for item in typed), counts


def _feature_names() -> tuple[str, ...]:
    names: tuple[str, ...] = (
        "static_instruction_count",
        "executed_instruction_count",
        "memory_event_count",
        "executed_fraction",
        "initial_rax_is_zero",
        "register_read_nonempty",
        "register_write_nonempty",
    )
    names += tuple(
        f"{field}::{value}"
        for field, values in _FIELD_VALUES.items()
        for value in values
    )
    return names


def _pair_features(
    reference: dict[str, float], variant: dict[str, float]
) -> tuple[float, ...]:
    names = _feature_names()
    values: list[float] = []
    for name in names:
        values.extend(
            (
                abs(reference[name] - variant[name]),
                reference[name] + variant[name],
            )
        )
    return tuple(values)


def _evaluate_pair(
    family: QuotientFamily,
    role: str,
    index: int,
    reference_code: bytes,
    variant_code: bytes,
) -> PairExample:
    reference_tokens: list[str] = []
    variant_tokens: list[str] = []
    reference_summary: dict[str, float] = {name: 0.0 for name in _feature_names()}
    variant_summary: dict[str, float] = {name: 0.0 for name in _feature_names()}
    observed_equal = True
    for initial_rax in INTERVENTIONS:
        ref_tokens, ref_summary = _trace_summary(reference_code, initial_rax)
        var_tokens, var_summary = _trace_summary(variant_code, initial_rax)
        reference_tokens.extend(ref_tokens)
        reference_tokens.append("<INTERVENTION>")
        variant_tokens.extend(var_tokens)
        variant_tokens.append("<INTERVENTION>")
        for name in reference_summary:
            reference_summary[name] += ref_summary[name]
            variant_summary[name] += var_summary[name]
        ref_trace = emulate_x86_64(reference_code, initial_rax=initial_rax)
        var_trace = emulate_x86_64(variant_code, initial_rax=initial_rax)
        observed_equal = observed_equal and ref_trace.final_rax == var_trace.final_rax
    return PairExample(
        family_id=family.family_id,
        split=family.split,
        variant_role=role,
        variant_index=index,
        label=int(observed_equal),
        reference_tokens=tuple(reference_tokens),
        variant_tokens=tuple(variant_tokens),
        feature_vector=_pair_features(reference_summary, variant_summary),
        reference_code=bytes(reference_code),
        variant_code=bytes(variant_code),
    )


@lru_cache(maxsize=1)
def _dataset() -> tuple[PairExample, ...]:
    """Generate the frozen 64-family, 64-pair-per-family benchmark."""

    rows: list[PairExample] = []
    for family in _family_specs():
        for index in range(64):
            role = "equivalent" if index % 2 == 0 else "near_miss"
            reference = _pad_nops(family.reference_code, (index // 4) % 4)
            variant_base = (
                family.equivalent_code
                if role == "equivalent"
                else family.near_miss_code
            )
            variant = _pad_nops(variant_base, index % 4)
            rows.append(_evaluate_pair(family, role, index, reference, variant))
    return tuple(rows)


def _token_vocabulary(rows: Sequence[PairExample]) -> dict[str, int]:
    tokens = sorted(
        {
            token
            for row in rows
            for token in (
                row.reference_tokens
                + row.variant_tokens
                + ("<REFERENCE>", "<VARIANT>", "<UNKNOWN>")
            )
        }
    )
    return {token: index for index, token in enumerate(tokens)}


def _sequence(row: PairExample) -> tuple[str, ...]:
    return ("<REFERENCE>",) + row.reference_tokens + ("<VARIANT>",) + row.variant_tokens


def _sigmoid(values: np.ndarray) -> np.ndarray:
    clipped = np.clip(values, -60.0, 60.0)
    return 1.0 / (1.0 + np.exp(-clipped))


def _fit_logistic(
    x_train: np.ndarray,
    y_train: np.ndarray,
    *,
    seed: int,
    l2: float = LOGISTIC_L2,
    learning_rate: float = LOGISTIC_LEARNING_RATE,
) -> tuple[np.ndarray, float, np.ndarray, np.ndarray]:
    mean = x_train.mean(axis=0)
    scale = x_train.std(axis=0)
    scale[scale < 1e-12] = 1.0
    x = (x_train - mean) / scale
    rng = np.random.default_rng(seed)
    weights: np.ndarray = np.asarray(rng.normal(0.0, 0.01, size=x.shape[1]))
    bias = 0.0
    for _ in range(LOGISTIC_EPOCHS):
        probability = _sigmoid(x @ weights + bias)
        error = probability - y_train
        weights -= learning_rate * ((x.T @ error) / len(x) + l2 * weights)
        bias -= learning_rate * float(error.mean())
    return weights, bias, mean, scale


def _predict_logistic(
    x: np.ndarray, model: tuple[np.ndarray, float, np.ndarray, np.ndarray]
) -> np.ndarray:
    weights, bias, mean, scale = model
    return _sigmoid(((x - mean) / scale) @ weights + bias)


def _fit_markov(
    train_rows: Sequence[PairExample], vocabulary: dict[str, int]
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    class_initial = np.ones((2, len(vocabulary)), dtype=float)
    class_transition = np.ones((2, len(vocabulary), len(vocabulary)), dtype=float)
    class_prior = np.ones(2, dtype=float)
    for row in train_rows:
        label = row.label
        tokens = _sequence(row)
        ids = [vocabulary.get(token, vocabulary["<UNKNOWN>"]) for token in tokens]
        class_prior[label] += 1.0
        class_initial[label, ids[0]] += 1.0
        for current, nxt in zip(ids, ids[1:]):
            class_transition[label, nxt, current] += 1.0
    class_initial /= class_initial.sum(axis=1, keepdims=True)
    class_transition /= class_transition.sum(axis=1, keepdims=True)
    class_prior /= class_prior.sum()
    return class_initial, class_transition, class_prior


def _predict_markov(
    rows: Sequence[PairExample],
    vocabulary: dict[str, int],
    model: tuple[np.ndarray, np.ndarray, np.ndarray],
) -> np.ndarray:
    initial, transition, prior = model
    probabilities: list[float] = []
    for row in rows:
        ids = [
            vocabulary.get(token, vocabulary["<UNKNOWN>"]) for token in _sequence(row)
        ]
        scores = np.log(prior.copy())
        for label in (0, 1):
            scores[label] += math.log(initial[label, ids[0]])
            scores[label] += sum(
                math.log(transition[label, nxt, current])
                for current, nxt in zip(ids, ids[1:])
            )
        probabilities.append(float(_sigmoid(np.asarray([scores[1] - scores[0]]))[0]))
    return np.asarray(probabilities, dtype=float)


def _rnn_forward(
    ids: Sequence[int],
    wxh: np.ndarray,
    whh: np.ndarray,
    why: np.ndarray,
    by: float,
) -> tuple[float, list[np.ndarray]]:
    hidden = np.zeros(wxh.shape[0], dtype=float)
    states: list[np.ndarray] = []
    for token_id in ids:
        previous = hidden
        hidden = np.tanh(wxh[:, token_id] + whh @ previous)
        states.append(np.concatenate((previous, hidden)))
    probability = float(_sigmoid(np.asarray([why @ hidden + by]))[0])
    return probability, states


def _fit_rnn(
    train_rows: Sequence[PairExample],
    vocabulary: dict[str, int],
    *,
    seed: int,
    hidden_size: int = RNN_HIDDEN_SIZE,
    epochs: int = RNN_EPOCHS,
    learning_rate: float = RNN_LEARNING_RATE,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, float, float]:
    rng = np.random.default_rng(seed)
    vocab_size = len(vocabulary)
    wxh = rng.normal(0.0, 0.05, size=(hidden_size, vocab_size))
    whh = rng.normal(0.0, 0.05, size=(hidden_size, hidden_size))
    why = rng.normal(0.0, 0.05, size=hidden_size)
    by = 0.0
    grouped_sequences: dict[tuple[int, ...], tuple[int, int]] = {}
    for row in train_rows:
        ids = tuple(
            vocabulary.get(token, vocabulary["<UNKNOWN>"]) for token in _sequence(row)
        )
        count, positives = grouped_sequences.get(ids, (0, 0))
        grouped_sequences[ids] = (count + 1, positives + row.label)
    for _ in range(epochs):
        gradient_wxh = np.zeros_like(wxh)
        gradient_whh = np.zeros_like(whh)
        gradient_why = np.zeros_like(why)
        gradient_by = 0.0
        for ids, (count, positives) in grouped_sequences.items():
            probability, states = _rnn_forward(ids, wxh, whh, why, by)
            delta = probability * count - positives
            gradient_why += delta * states[-1][hidden_size:]
            gradient_by += float(delta)
            dh = delta * why
            for index in range(len(ids) - 1, -1, -1):
                previous, hidden = (
                    states[index][:hidden_size],
                    states[index][hidden_size:],
                )
                dtanh = dh * (1.0 - hidden * hidden)
                gradient_wxh[:, ids[index]] += dtanh
                gradient_whh += np.outer(dtanh, previous)
                dh = whh.T @ dtanh
        scale = 1.0 / max(len(train_rows), 1)
        wxh -= learning_rate * gradient_wxh * scale
        whh -= learning_rate * gradient_whh * scale
        why -= learning_rate * gradient_why * scale
        by -= learning_rate * gradient_by * scale
    return wxh, whh, why, by, float(hidden_size)


def _predict_rnn(
    rows: Sequence[PairExample],
    vocabulary: dict[str, int],
    model: tuple[np.ndarray, np.ndarray, np.ndarray, float, float],
) -> np.ndarray:
    wxh, whh, why, by, _ = model
    return np.asarray(
        [
            _rnn_forward(
                [
                    vocabulary.get(token, vocabulary["<UNKNOWN>"])
                    for token in _sequence(row)
                ],
                wxh,
                whh,
                why,
                by,
            )[0]
            for row in rows
        ],
        dtype=float,
    )


def _split_manifest_sha256(assignment: dict[str, str]) -> str:
    """Hash the sealed split assignment over a canonical sorted serialization."""

    canonical = "".join(
        f"{family_id}\t{split}\n" for family_id, split in sorted(assignment.items())
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _split_manifest() -> dict[str, Any]:
    """Seal the frozen family-to-split assignment exactly as _family_specs emits it."""

    assignment = {family.family_id: family.split for family in _family_specs()}
    family_ids_per_split = {
        split: [
            family_id for family_id, assigned in assignment.items() if assigned == split
        ]
        for split in SPLIT_NAMES
    }
    return {
        "assignment": assignment,
        "family_ids_per_split": family_ids_per_split,
        "sha256": _split_manifest_sha256(assignment),
        "canonicalization": (
            "sha256 over 'family_id\\tsplit\\n' lines ordered by sorted family_id"
        ),
    }


def _logit(probabilities: np.ndarray) -> np.ndarray:
    clipped = np.clip(np.asarray(probabilities, dtype=float), 1e-12, 1.0 - 1e-12)
    return np.log(clipped / (1.0 - clipped))


def _fit_platt(probabilities: np.ndarray, labels: np.ndarray) -> tuple[float, float]:
    """Fit a deterministic 1-D Platt scaling on development log-odds.

    Fixed-epoch gradient descent from the identity map; no randomness, so the
    calibration parameters are a pure function of the development rows.
    """

    features = _logit(probabilities)
    targets = np.asarray(labels, dtype=float)
    a = 0.0
    b = 0.0
    for _ in range(PLATT_EPOCHS):
        error = _sigmoid(a * features + b) - targets
        a -= PLATT_LEARNING_RATE * float(np.mean(error * features))
        b -= PLATT_LEARNING_RATE * float(np.mean(error))
    return float(a), float(b)


def _apply_platt(probabilities: np.ndarray, a: float, b: float) -> np.ndarray:
    return _sigmoid(a * _logit(probabilities) + b)


def _fit_with_starts(
    fitter: Callable[[int], Any],
    development_scorer: Callable[[Any], float],
    *,
    starts: tuple[int, ...] = SEEDS,
) -> dict[str, Any]:
    """Fit at every deterministic start and select on development rows only.

    Selection rule: best development balanced accuracy; ties resolve to the
    lowest seed because starts are iterated in ascending order and a strictly
    greater score is required to replace the incumbent.
    """

    catalog = [int(seed) for seed in starts]
    development_score_by_start: dict[str, float] = {}
    selected_start: int | None = None
    best = -1.0
    for seed in catalog:
        score = float(development_scorer(fitter(seed)))
        development_score_by_start[str(seed)] = score
        if selected_start is None or score > best:
            selected_start = seed
            best = score
    return {
        "catalog": catalog,
        "selection_rule": STARTS_SELECTION_RULE,
        "selected_start": selected_start,
        "development_score_by_start": development_score_by_start,
    }


def _select_hyperparameters(
    train_rows: Sequence[PairExample],
    development_rows: Sequence[PairExample],
    train_matrix: np.ndarray,
    development_matrix: np.ndarray,
    vocabulary: dict[str, int],
) -> dict[str, Any]:
    """Development-only hyperparameter selection; held-out rows are never an input.

    Options are iterated in the declared grid order and a strictly greater
    development balanced accuracy is required to replace the incumbent, so ties
    resolve to the lexicographically first option.
    """

    train_labels = np.asarray([row.label for row in train_rows], dtype=float)
    development_labels = np.asarray(
        [row.label for row in development_rows], dtype=float
    )
    logistic_grid = {
        "l2": list(LOGISTIC_L2_GRID),
        "learning_rate": list(LOGISTIC_LEARNING_RATE_GRID),
    }
    rnn_grid = {
        "hidden_size": list(RNN_HIDDEN_SIZE_GRID),
        "epochs": list(RNN_EPOCHS_GRID),
    }
    logistic_scores: dict[str, float] = {}
    logistic_selected: dict[str, float] | None = None
    logistic_best = -1.0
    for l2 in LOGISTIC_L2_GRID:
        for learning_rate in LOGISTIC_LEARNING_RATE_GRID:
            option = f"l2={l2}|learning_rate={learning_rate}"
            model = _fit_logistic(
                train_matrix,
                train_labels,
                seed=RNG_SEED,
                l2=float(l2),
                learning_rate=float(learning_rate),
            )
            score = float(
                _metrics(
                    development_labels,
                    _predict_logistic(development_matrix, model),
                    extended=False,
                )["balanced_accuracy"]
            )
            logistic_scores[option] = score
            if logistic_selected is None or score > logistic_best:
                logistic_selected = {
                    "l2": float(l2),
                    "learning_rate": float(learning_rate),
                }
                logistic_best = score
    rnn_scores: dict[str, float] = {}
    rnn_selected: dict[str, int] | None = None
    rnn_best = -1.0
    for hidden_size in RNN_HIDDEN_SIZE_GRID:
        for epochs in RNN_EPOCHS_GRID:
            option = f"hidden_size={hidden_size}|epochs={epochs}"
            rnn_model = _fit_rnn(
                train_rows,
                vocabulary,
                seed=RNG_SEED,
                hidden_size=int(hidden_size),
                epochs=int(epochs),
            )
            score = float(
                _metrics(
                    development_labels,
                    _predict_rnn(development_rows, vocabulary, rnn_model),
                    extended=False,
                )["balanced_accuracy"]
            )
            rnn_scores[option] = score
            if rnn_selected is None or score > rnn_best:
                rnn_selected = {
                    "hidden_size": int(hidden_size),
                    "epochs": int(epochs),
                }
                rnn_best = score
    return {
        "policy": "development_only_selection",
        "fit_split": "development",
        "test_rows_used": 0,
        "tie_rule": HYPERPARAMETER_TIE_RULE,
        "grid": {
            "calibrated_interpretable": logistic_grid,
            "temporal_probabilistic": [],
            "neural_sequence": rnn_grid,
        },
        "scores_by_option": {
            "calibrated_interpretable": logistic_scores,
            "neural_sequence": rnn_scores,
        },
        "selected_per_model": {
            "calibrated_interpretable": logistic_selected,
            "temporal_probabilistic": None,
            "neural_sequence": rnn_selected,
        },
        "closed_form_note": (
            "temporal_probabilistic is a closed-form smoothed count estimator "
            "with no tunable hyperparameters"
        ),
    }


def _family_shuffle_control(
    test_rows: Sequence[PairExample],
    test_matrix: np.ndarray,
    *,
    seed: int = FAMILY_SHUFFLE_SEED,
) -> dict[str, Any]:
    """Scramble within-family label correspondence in a held-out refit diagnostic.

    Seeded permutations preserve each family's class totals. The interpretable
    model refits on the same held-out rows with scrambled labels and is scored
    against their original labels. This deliberately in-sample perturbation is
    not an out-of-sample prediction, does not remove family-prevalence
    associations, and cannot certify absence of leakage.
    """

    family_ids = sorted({row.family_id for row in test_rows})
    blocks = {
        family: [
            index for index, row in enumerate(test_rows) if row.family_id == family
        ]
        for family in family_ids
    }
    labels = np.asarray([row.label for row in test_rows], dtype=float)
    rng = np.random.default_rng(seed)
    shuffled_labels = labels.copy()
    for family in family_ids:
        block = blocks[family]
        shuffled_labels[block] = rng.permutation(labels[block])
    model = _fit_logistic(test_matrix, shuffled_labels, seed=seed)
    predictions = _predict_logistic(test_matrix, model)
    metrics = _metrics(labels, predictions, extended=False)
    return {
        "metrics": metrics,
        "seed": int(seed),
        "permuted_family_count": len(family_ids),
        "fit_scope": "held_out_in_sample_perturbation_only",
        "preserves_family_class_totals": True,
        "description": (
            "within-family label correspondence is scrambled while preserving "
            "family class totals; the interpretable model refits on those same "
            "held-out rows with scrambled labels and scores their original "
            "labels. This is not an out-of-sample prediction or proof that "
            "family-prevalence leakage is absent."
        ),
    }


def _opcode_only_tokens(tokens: Sequence[str]) -> tuple[str, ...]:
    """Reduce typed tokens to the instruction-family (opcode surface) field."""

    index = TYPED_OBSERVATION_FIELDS.index("instruction_family")
    return tuple(token.split("|")[index] if "|" in token else token for token in tokens)


def _opcode_only_rows(
    rows: Sequence[PairExample],
) -> tuple[PairExample, ...]:
    return tuple(
        replace(
            row,
            reference_tokens=_opcode_only_tokens(row.reference_tokens),
            variant_tokens=_opcode_only_tokens(row.variant_tokens),
        )
        for row in rows
    )


def _opcode_only_vocabulary(
    rows: Sequence[PairExample],
) -> dict[str, int]:
    tokens = sorted(
        {
            token
            for row in rows
            for token in (
                _opcode_only_tokens(row.reference_tokens)
                + _opcode_only_tokens(row.variant_tokens)
                + ("<REFERENCE>", "<VARIANT>", "<UNKNOWN>")
            )
        }
    )
    return {token: index for index, token in enumerate(tokens)}


def _leakage_probe_scores(
    train_rows: Sequence[PairExample],
    test_rows: Sequence[PairExample],
    train_matrix: np.ndarray,
    test_matrix: np.ndarray,
    vocabulary: dict[str, int],
    *,
    rnn_hidden_size: int,
    rnn_epochs: int,
) -> dict[str, Any]:
    """Bounded encoding/opcode-surface-only ablation for each co-primary model.

    The probe is deliberately bounded: it refits each co-primary model on
    opcode-surface information only (instruction-family fields and static
    counters) and scores the ablated models against true held-out labels.  It
    supports no architecture-metadata conclusion either way.
    """

    train_labels = np.asarray([row.label for row in train_rows], dtype=float)
    test_labels = np.asarray([row.label for row in test_rows], dtype=float)
    surface = _surface_indices()
    opcode_train = _opcode_only_rows(train_rows)
    opcode_test = _opcode_only_rows(test_rows)
    opcode_vocabulary = _opcode_only_vocabulary(train_rows)
    held_out_scores: dict[str, float] = {}
    logistic_model = _fit_logistic(
        train_matrix[:, surface], train_labels, seed=RNG_SEED
    )
    held_out_scores["calibrated_interpretable"] = float(
        _metrics(
            test_labels,
            _predict_logistic(test_matrix[:, surface], logistic_model),
            extended=False,
        )["balanced_accuracy"]
    )
    markov_model = _fit_markov(opcode_train, opcode_vocabulary)
    held_out_scores["temporal_probabilistic"] = float(
        _metrics(
            test_labels,
            _predict_markov(opcode_test, opcode_vocabulary, markov_model),
            extended=False,
        )["balanced_accuracy"]
    )
    rnn_model = _fit_rnn(
        opcode_train,
        opcode_vocabulary,
        seed=RNG_SEED,
        hidden_size=int(rnn_hidden_size),
        epochs=int(rnn_epochs),
    )
    held_out_scores["neural_sequence"] = float(
        _metrics(
            test_labels,
            _predict_rnn(opcode_test, opcode_vocabulary, rnn_model),
            extended=False,
        )["balanced_accuracy"]
    )
    return {
        "held_out_scores": held_out_scores,
        "feature_sets": {
            "calibrated_interpretable": (
                "typed-pair feature columns restricted to the encoding/opcode "
                "surface indices (instruction-family and static executed counters)"
            ),
            "temporal_probabilistic": (
                "typed tokens reduced to the instruction_family field only"
            ),
            "neural_sequence": (
                "typed tokens reduced to the instruction_family field only"
            ),
        },
    }


def _cross_encoding_consistency(rows: Sequence[PairExample]) -> dict[str, Any]:
    """Name the benchmark's existing cross-encoding consistency contract.

    Equivalent-role rows pair distinct machine encodings of the same formal
    transformation, and labels come from the declared output relation under
    real bounded emulation.  Consistency therefore means the recorded label
    assignment does not depend on which encoding was used: every equivalent
    row is labeled 1 and every near-miss row 0, per family.
    """

    family_ids = sorted({row.family_id for row in rows})
    consistent = 0
    for family in family_ids:
        members = [row for row in rows if row.family_id == family]
        equivalent = [row for row in members if row.variant_role == "equivalent"]
        near_miss = [row for row in members if row.variant_role == "near_miss"]
        encodings_differ = any(
            row.reference_code != row.variant_code for row in equivalent
        )
        labels_match_relation = all(row.label == 1 for row in equivalent) and all(
            row.label == 0 for row in near_miss
        )
        if encodings_differ and labels_match_relation:
            consistent += 1
    return {
        "check": "cross_encoding_label_consistency",
        "description": (
            "existing cross-encoding consistency contract: equivalent-role rows "
            "pair distinct encodings of one formal transformation and labels "
            "must equal the formal output relation regardless of encoding"
        ),
        "consistent_family_count": consistent,
        "consistent_family_rate": float(consistent / len(family_ids))
        if family_ids
        else 0.0,
        "family_count": len(family_ids),
    }


