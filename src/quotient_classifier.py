def _near_duplicate_report(rows: Sequence[PairExample]) -> dict[str, Any]:
    """Screen cross-split family pairs for near-duplicate leakage surfaces.

    Two bounded similarity metrics are computed per cross-split family pair:
    byte identity (Jaccard over the padded reference/variant code sets) and
    typed-token Jaccard.  A pair is flagged when either exceeds the declared
    threshold; flagged pairs are declared only when both families share the
    same frozen near-duplicate template key, because the benchmark
    deliberately repeats effect templates with different constants across
    splits while keeping family identity split-disjoint.
    """

    by_family: dict[str, list[PairExample]] = {}
    for row in rows:
        by_family.setdefault(row.family_id, []).append(row)
    family_ids = list(by_family)
    code_sets = {
        family_id: {
            code
            for row in by_family[family_id]
            for code in (row.reference_code, row.variant_code)
        }
        for family_id in family_ids
    }
    token_sets = {
        family_id: {
            token
            for row in by_family[family_id]
            for token in (*row.reference_tokens, *row.variant_tokens)
        }
        for family_id in family_ids
    }
    flagged_pairs: list[dict[str, Any]] = []
    max_similarity = 0.0
    max_pair: dict[str, Any] | None = None
    cross_split_pair_count = 0
    for a_position, family_a in enumerate(family_ids):
        for family_b in family_ids[a_position + 1 :]:
            split_a = by_family[family_a][0].split
            split_b = by_family[family_b][0].split
            if split_a == split_b:
                continue
            cross_split_pair_count += 1
            code_union = code_sets[family_a] | code_sets[family_b]
            byte_identity = (
                len(code_sets[family_a] & code_sets[family_b]) / len(code_union)
                if code_union
                else 0.0
            )
            token_union = token_sets[family_a] | token_sets[family_b]
            token_jaccard = (
                len(token_sets[family_a] & token_sets[family_b]) / len(token_union)
                if token_union
                else 0.0
            )
            similarity = max(byte_identity, token_jaccard)
            if similarity > max_similarity:
                max_similarity = similarity
                max_pair = {"family_a": family_a, "family_b": family_b}
            if similarity > NEAR_DUPLICATE_THRESHOLD:
                key_a = _near_duplicate_template_key(family_a)
                key_b = _near_duplicate_template_key(family_b)
                flagged_pairs.append(
                    {
                        "family_a": family_a,
                        "family_b": family_b,
                        "split_a": split_a,
                        "split_b": split_b,
                        "byte_identity": float(byte_identity),
                        "token_jaccard": float(token_jaccard),
                        "similarity": float(similarity),
                        "crosses_training_held_out": bool(
                            {split_a, split_b} == {"training", "held_out"}
                        ),
                        "template_keys": [key_a, key_b],
                        "declared": bool(key_a == key_b),
                    }
                )
    return {
        "metrics": ["byte_identity", "token_jaccard"],
        "threshold": NEAR_DUPLICATE_THRESHOLD,
        "comparison_unit": (
            "cross-split family pairs over padded code sets and typed-token sets"
        ),
        "declaration_rule": (
            "a flagged pair is declared iff both families share the same frozen "
            "near-duplicate template key; undeclared flagged pairs fail closed"
        ),
        "cross_split_pair_count": cross_split_pair_count,
        "flagged_pair_count": len(flagged_pairs),
        "flagged_pairs": flagged_pairs,
        "max_cross_split_similarity": float(max_similarity),
        "max_cross_split_pair": max_pair,
    }


def _wilson_interval(successes: int, total: int) -> list[float]:
    """Return a 95% Wilson interval for one Bernoulli proportion."""

    if total <= 0:
        return [float("nan"), float("nan")]
    z = 1.959963984540054
    proportion = successes / total
    denominator = 1.0 + z**2 / total
    center = (proportion + z**2 / (2.0 * total)) / denominator
    radius = (
        z
        * math.sqrt(proportion * (1.0 - proportion) / total + z**2 / (4.0 * total**2))
        / denominator
    )
    return [float(max(0.0, center - radius)), float(min(1.0, center + radius))]


def _adjusted_mutual_information(labels: np.ndarray, predictions: np.ndarray) -> float:
    """Compute adjusted mutual information for the binary endpoint.

    The expected mutual information is evaluated under the fixed row/column
    margins, using the hypergeometric null.  This is deliberately implemented
    locally so the receipt does not depend on a hidden third-party metric
    implementation.
    """

    observed = np.zeros((2, 2), dtype=int)
    for label, prediction in zip(
        labels.astype(int), predictions.astype(int), strict=True
    ):
        observed[int(label), int(prediction)] += 1
    total = int(observed.sum())
    if total == 0:
        return 0.0
    row_sums = observed.sum(axis=1)
    column_sums = observed.sum(axis=0)

    def mutual_information(table: np.ndarray) -> float:
        n = int(table.sum())
        if n == 0:
            return 0.0
        rows = table.sum(axis=1)
        columns = table.sum(axis=0)
        value = 0.0
        for i in range(table.shape[0]):
            for j in range(table.shape[1]):
                cell = int(table[i, j])
                if cell and rows[i] and columns[j]:
                    value += (cell / n) * math.log(
                        (n * cell) / (int(rows[i]) * int(columns[j]))
                    )
        return value

    mi = mutual_information(observed)
    expected_mi = 0.0
    for row_total in row_sums:
        for column_total in column_sums:
            row_count = int(row_total)
            column_count = int(column_total)
            if row_count == 0 or column_count == 0:
                continue
            denominator = math.comb(total, column_count)
            lower = max(0, row_count + column_count - total)
            upper = min(row_count, column_count)
            for cell in range(lower, upper + 1):
                probability = (
                    math.comb(row_count, cell)
                    * math.comb(total - row_count, column_count - cell)
                    / denominator
                )
                if cell:
                    expected_mi += (
                        probability
                        * (cell / total)
                        * math.log((total * cell) / (row_count * column_count))
                    )
    entropy_rows = -sum(
        (count / total) * math.log(count / total) for count in row_sums if count
    )
    entropy_columns = -sum(
        (count / total) * math.log(count / total) for count in column_sums if count
    )
    denominator = max(entropy_rows, entropy_columns) - expected_mi
    return float((mi - expected_mi) / denominator) if denominator > 1e-12 else 1.0


def _metrics(
    labels: np.ndarray, probabilities: np.ndarray, *, extended: bool = True
) -> dict[str, Any]:
    predictions = probabilities >= 0.5
    labels_bool = labels.astype(bool)
    true_positive = int(np.sum(predictions & labels_bool))
    true_negative = int(np.sum(~predictions & ~labels_bool))
    false_positive = int(np.sum(predictions & ~labels_bool))
    false_negative = int(np.sum(~predictions & labels_bool))
    positive_total = true_positive + false_negative
    negative_total = true_negative + false_positive
    positive_recall = true_positive / positive_total if positive_total else 0.0
    negative_recall = true_negative / negative_total if negative_total else 0.0
    balanced_accuracy = (positive_recall + negative_recall) / 2.0
    f1_values: list[float] = []
    for positive in (False, True):
        tp = true_positive if positive else true_negative
        fp = false_positive if positive else false_negative
        fn = false_negative if positive else false_positive
        denominator = 2 * tp + fp + fn
        f1_values.append(2 * tp / denominator if denominator else 0.0)
    bins = np.linspace(0.0, 1.0, 11)
    calibration_error = 0.0
    for lower, upper in zip(bins[:-1], bins[1:]):
        mask = (probabilities >= lower) & (
            probabilities < upper if upper < 1.0 else probabilities <= upper
        )
        if np.any(mask):
            calibration_error += float(mask.mean()) * abs(
                float(probabilities[mask].mean()) - float(labels[mask].mean())
            )
    result: dict[str, Any] = {
        "balanced_accuracy": float(balanced_accuracy),
        "macro_f1": float(np.mean(f1_values)),
        "brier_score": float(np.mean((probabilities - labels) ** 2)),
        "expected_calibration_error": float(calibration_error),
        "confusion_matrix": {
            "true_negative": true_negative,
            "false_positive": false_positive,
            "false_negative": false_negative,
            "true_positive": true_positive,
        },
        "false_equivalence_rate": float(
            false_positive / negative_total if negative_total else 0.0
        ),
        "false_distinction_rate": float(
            false_negative / positive_total if positive_total else 0.0
        ),
        "rows": len(labels),
        "positive_rows": int(labels.sum()),
        "negative_rows": int(len(labels) - labels.sum()),
        "wilson_intervals": {
            "equivalence_recall": _wilson_interval(true_positive, positive_total),
            "near_miss_separation": _wilson_interval(true_negative, negative_total),
        },
    }
    if extended:
        confidence = np.maximum(probabilities, 1.0 - probabilities)
        selected = confidence >= 0.75
        selected_count = int(selected.sum())
        result.update(
            {
                "adjusted_mutual_information": _adjusted_mutual_information(
                    labels, predictions
                ),
                "posterior_equivalence_consistency": float(
                    np.mean(probabilities[labels_bool])
                )
                if positive_total
                else None,
                "near_miss_separation_rate": float(negative_recall),
                "selective_risk_coverage": {
                    "confidence_threshold": 0.75,
                    "coverage": float(selected.mean()) if len(selected) else 0.0,
                    "risk": float(
                        np.mean(predictions[selected] != labels_bool[selected])
                    )
                    if selected_count
                    else None,
                    "selected_rows": selected_count,
                },
            }
        )
    return result


def _family_confusion_counts(
    rows: Sequence[PairExample], probabilities: np.ndarray
) -> np.ndarray:
    """Sufficient counts for exact rescoring of any complete-family sample."""
    families = sorted({row.family_id for row in rows})
    labels = np.asarray([row.label for row in rows], dtype=bool)
    predictions = np.asarray(probabilities) >= 0.5
    counts = []
    for family in families:
        mask = np.asarray([row.family_id == family for row in rows])
        counts.append(
            [
                np.sum(mask & ~labels & ~predictions),
                np.sum(mask & ~labels & predictions),
                np.sum(mask & labels & ~predictions),
                np.sum(mask & labels & predictions),
            ]
        )
    return np.asarray(counts, dtype=float)


def _primary_metrics_from_confusion(counts: np.ndarray) -> dict[str, np.ndarray]:
    """Vectorized balanced accuracy and macro-F1 with the metric's zero rule."""
    tn, fp, fn, tp = counts.T

    def ratio(numerator: np.ndarray, denominator: np.ndarray) -> np.ndarray:
        return np.divide(
            numerator, denominator, out=np.zeros_like(numerator), where=denominator > 0
        )

    return {
        "balanced_accuracy": (ratio(tp, tp + fn) + ratio(tn, tn + fp)) / 2,
        "macro_f1": (ratio(2 * tp, 2 * tp + fp + fn) + ratio(2 * tn, 2 * tn + fp + fn))
        / 2,
    }


def _cluster_bootstrap(
    rows: Sequence[PairExample],
    probabilities: np.ndarray,
    *,
    seed: int,
    replicates: int = BOOTSTRAP_REPLICATES,
) -> dict[str, list[float]]:
    counts = _family_confusion_counts(rows, probabilities)
    samples = np.random.default_rng(seed).integers(
        0, len(counts), size=(replicates, len(counts))
    )
    metrics = _primary_metrics_from_confusion(counts[samples].sum(axis=1))
    return {metric: values.tolist() for metric, values in metrics.items()}


def _paired_family_randomization(
    rows: Sequence[PairExample],
    model_probabilities: np.ndarray,
    baseline_probabilities: np.ndarray,
    *,
    seed: int,
    replicates: int = BOOTSTRAP_REPLICATES,
) -> dict[str, Any]:
    """Swap whole prediction blocks under a paired family-exchangeability null.

    All rows in a source family share one swap, preserving within-family
    dependence. This conditional test concerns these frozen predictions; it
    does not incorporate model-fitting variability or establish external
    validity. Inclusive ties and the Monte Carlo plus-one rule avoid zero
    p-values. The bootstrap distribution remains an interval diagnostic.
    """

    if (
        not rows
        or isinstance(replicates, bool)
        or not isinstance(replicates, int)
        or replicates <= 0
    ):
        raise ValueError("rows and a positive integer replicate count are required")
    labels = np.asarray([row.label for row in rows], dtype=float)
    arrays = [
        np.asarray(p, dtype=float)
        for p in (model_probabilities, baseline_probabilities)
    ]
    if any(
        p.shape != labels.shape
        or not np.all(np.isfinite(p))
        or np.any((p < 0) | (p > 1))
        for p in arrays
    ):
        raise ValueError(
            "probabilities must be finite [0, 1] vectors aligned with rows"
        )
    if np.any((labels != 0) & (labels != 1)):
        raise ValueError("labels must be binary")
    families = sorted({row.family_id for row in rows})
    model_counts = _family_confusion_counts(rows, arrays[0])
    baseline_counts = _family_confusion_counts(rows, arrays[1])
    swaps = np.random.default_rng(seed).integers(0, 2, size=(replicates, len(families)))
    differences = model_counts - baseline_counts
    null_model = model_counts.sum(axis=0) - swaps @ differences
    null_baseline = baseline_counts.sum(axis=0) + swaps @ differences
    null_model_metrics, null_baseline_metrics = (
        _primary_metrics_from_confusion(null_model),
        _primary_metrics_from_confusion(null_baseline),
    )
    observed_model = _metrics(labels, arrays[0], extended=False)
    observed_baseline = _metrics(labels, arrays[1], extended=False)
    observed = {
        metric: float(observed_model[metric] - observed_baseline[metric])
        for metric in PRIMARY_METRICS
    }
    exceedances = {
        metric: int(
            np.sum(
                null_model_metrics[metric] - null_baseline_metrics[metric]
                >= observed[metric] - 1e-12
            )
        )
        for metric in PRIMARY_METRICS
    }
    return {
        "method": "paired_source_family_prediction_swap_monte_carlo",
        "null": "model_and_baseline_prediction_blocks_exchangeable_within_source_family",
        "alternative": "model_minus_baseline_metric_greater_than_zero",
        "sampling_unit": "source_family",
        "family_count": len(families),
        "replicates": replicates,
        "seed": seed,
        "ties": "inclusive_with_1e-12_numerical_tolerance",
        "p_value_rule": "(exceedances + 1) / (replicates + 1)",
        "observed_difference": observed,
        "exceedances": exceedances,
        "p_values": {
            metric: (count + 1) / (replicates + 1)
            for metric, count in exceedances.items()
        },
        "limitations": "Conditional on frozen fitted predictions and family exchangeability; no population or model-refitting uncertainty.",
    }


def _paired_cluster_bootstrap(
    rows: Sequence[PairExample],
    model_probabilities: np.ndarray,
    baseline_probabilities: np.ndarray,
    *,
    seed: int,
    replicates: int = BOOTSTRAP_REPLICATES,
) -> dict[str, Any]:
    """Bootstrap paired model-minus-baseline metrics by source family."""

    families = sorted({row.family_id for row in rows})
    labels = np.asarray([row.label for row in rows], dtype=float)
    observed_model = _metrics(labels, model_probabilities, extended=False)
    observed_baseline = _metrics(labels, baseline_probabilities, extended=False)
    observed = {
        metric: float(observed_model[metric] - observed_baseline[metric])
        for metric in PRIMARY_METRICS
    }
    model_counts = _family_confusion_counts(rows, model_probabilities)
    baseline_counts = _family_confusion_counts(rows, baseline_probabilities)
    samples = np.random.default_rng(seed).integers(
        0, len(families), size=(replicates, len(families))
    )
    model_metrics = _primary_metrics_from_confusion(model_counts[samples].sum(axis=1))
    baseline_metrics = _primary_metrics_from_confusion(
        baseline_counts[samples].sum(axis=1)
    )
    values = {
        metric: (model_metrics[metric] - baseline_metrics[metric]).tolist()
        for metric in PRIMARY_METRICS
    }
    intervals = {
        metric: _interval(metric_values) for metric, metric_values in values.items()
    }
    nonpositive_fractions = {
        metric: float(sum(value <= 0.0 for value in draws) / len(draws))
        for metric, draws in values.items()
    }
    randomization = _paired_family_randomization(
        rows,
        model_probabilities,
        baseline_probabilities,
        seed=seed,
        replicates=replicates,
    )
    return {
        "family_count": len(families),
        "bootstrap_replicates": replicates,
        "observed_difference": observed,
        "confidence_intervals": {
            metric: {"confidence_level": CONFIDENCE_LEVEL, "interval": interval}
            for metric, interval in intervals.items()
        },
        "nonpositive_bootstrap_fractions": nonpositive_fractions,
        "randomization_test": randomization,
        "sampling_unit": "source_family",
    }


def _interval(values: Sequence[float]) -> list[float]:
    return [
        float(np.quantile(np.asarray(values, dtype=float), 0.025)),
        float(np.quantile(np.asarray(values, dtype=float), 0.975)),
    ]


def _evaluate(
    name: str,
    rows: Sequence[PairExample],
    probabilities: np.ndarray,
    *,
    seed: int,
) -> dict[str, Any]:
    labels = np.asarray([row.label for row in rows], dtype=float)
    summary = _metrics(labels, probabilities)
    bootstrap = _cluster_bootstrap(rows, probabilities, seed=seed)
    summary["confidence_intervals"] = {
        metric: {"confidence_level": CONFIDENCE_LEVEL, "interval": _interval(values)}
        for metric, values in bootstrap.items()
    }
    summary["family_count"] = len({row.family_id for row in rows})
    summary["model_family"] = name
    return summary


def _holm_adjust(p_values: dict[str, float]) -> dict[str, float]:
    """Apply deterministic Holm step-down adjustment to a comparison family."""

    ordered = sorted(p_values.items(), key=lambda item: (item[1], item[0]))
    adjusted: dict[str, float] = {}
    running = 0.0
    total = len(ordered)
    for rank, (key, value) in enumerate(ordered, start=1):
        running = max(running, min(1.0, float(value) * (total - rank + 1)))
        adjusted[key] = running
    return adjusted


