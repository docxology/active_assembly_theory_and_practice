"""Leakage-safe classifiers for bounded formal-quotient membership.

The endpoint is deliberately pairwise: a classifier predicts whether two
programs occupy the same bounded quotient under the declared final-output
relation and intervention catalog.  This makes source-family holdout
meaningful even when a held-out family has a behavior signature not seen during
training.  Labels are generated by the formal witness evaluator; neither
mnemonic names nor model output define the target.

Three deliberately small CPU-runnable model families are evaluated together:

* a regularized logistic classifier over typed pair summaries;
* a class-conditional first-order Markov likelihood over typed token pairs;
* a one-layer tanh recurrent classifier implemented with NumPy and explicit
  back-propagation through time.

The module is a bounded research endpoint, not a reverse-engineering system.
Unsupported instructions and insufficient strata remain explicit in receipts.
"""

